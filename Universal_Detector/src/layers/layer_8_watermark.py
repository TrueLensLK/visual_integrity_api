# L8-2: AI LOGO / TEXT DETECTION
# ============================================================================

def detect_ai_text_markers(gray: np.ndarray) -> Dict:
    """
    L8-2 FIX: Detect AI generator text/logos in the image.

    Uses:
      1. MSER text region detection (finds text-like blobs)
      2. Edge-based logo detection in high-contrast small regions
      3. Pattern matching for known AI badge shapes

    Note: Full OCR (Tesseract) is optional - we detect text-like regions
    and check structural patterns even without OCR.

    Returns:
        Dict with score and description
    """
    h, w = gray.shape

    # ---- 1. MSER text region detection ----
    mser = cv2.MSER_create()
    mser.setMinArea(30)
    mser.setMaxArea(min(2000, h * w // 20))

    try:
        regions, _ = mser.detectRegions(gray)
    except Exception:
        regions = []

    # Count text-like regions in corners (AI badges are small text in corners)
    corner_text_count = 0
    margin_y = max(int(h * 0.12), 40)
    margin_x = max(int(w * 0.12), 40)

    for region in regions:
        # Bounding box of each MSER region
        x_coords = region[:, 0]
        y_coords = region[:, 1]
        rx, ry = int(np.mean(x_coords)), int(np.mean(y_coords))

        # Is it in a corner?
        in_corner = (
            (ry < margin_y or ry > h - margin_y) and
            (rx < margin_x or rx > w - margin_x)
        )
        if in_corner:
            corner_text_count += 1

    # ---- 2. Midjourney 2x2 grid detection ----
    # Midjourney v5/v6 outputs a 2x2 grid. Check for strong horizontal and
    # vertical lines at h/2 and w/2
    grid_detected = False
    if h > 256 and w > 256:
        mid_h_strip = gray[h // 2 - 2: h // 2 + 2, :]
        mid_v_strip = gray[:, w // 2 - 2: w // 2 + 2]
        h_var = float(np.var(mid_h_strip))
        v_var = float(np.var(mid_v_strip))
        # A sharp grid line → very low variance in that strip
        if h_var < 50 and v_var < 50:
            grid_detected = True

    # ---- 3. Try OCR if pytesseract is available ----
    ocr_ai_found = False
    ocr_text = ""
    try:
        import pytesseract
        # Only OCR the corners (fast, targeted)
        corner_regions = [
            gray[:margin_y, :margin_x],
            gray[:margin_y, w - margin_x:],
            gray[h - margin_y:, :margin_x],
            gray[h - margin_y:, w - margin_x:],
            gray[h - margin_y:, w // 4: 3 * w // 4],  # bottom center
        ]
        for cr in corner_regions:
            if cr.size < 100:
                continue
            text = pytesseract.image_to_string(cr, config="--psm 7").lower().strip()
            if text:
                ocr_text += text + " "
                for pattern in AI_TEXT_PATTERNS:
                    if pattern in text:
                        ocr_ai_found = True
                        break
                if not ocr_ai_found:
                    for frag in AI_BADGE_FRAGMENTS:
                        if frag in text.split():
                            ocr_ai_found = True
                            break
            if ocr_ai_found:
                break
    except ImportError:
        pass  # pytesseract not installed - that's fine
    except Exception:
        pass

    # ---- Scoring ----
    score = 0
    reasons = []

    if ocr_ai_found:
        score -= 35
        reasons.append(f"AI text detected: '{ocr_text.strip()[:60]}'")

    if grid_detected:
        score -= 20
        reasons.append("Midjourney-style 2x2 grid")

    if corner_text_count > 50:
        score -= 15
        reasons.append(f"Dense text in corners ({corner_text_count} regions)")
    elif corner_text_count > 20:
        score -= 8
        reasons.append(f"Text-like regions in corners ({corner_text_count})")

    if not reasons:
        return {"score": 0, "description": "No AI text/logo markers"}

    return {
        "score": max(score, -45),
        "description": "; ".join(reasons),
        "corner_text_count": corner_text_count,
        "grid_detected": grid_detected,
        "ocr_ai_found": ocr_ai_found,
    }


