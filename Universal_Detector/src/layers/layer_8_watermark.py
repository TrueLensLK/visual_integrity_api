def detect_watermarks(image_path: str, is_jpeg: bool = False) -> Tuple[float, str]:
    """
    Layer 8: Complete Watermark & Digital Signature Detection

    Combines all 6 detection methods:
      1. Full-image visible watermark scan        (L8-1)
      2. AI logo/text detection (MSER + OCR)      (L8-2)
      3. Steganography (LSB + chi² + DCT)         (L8-3)
      4. Hash-based watermark detection            (L8-4)
      5. SynthID / Stable Signature detection      (L8-5)
      6. Calibrated FFT invisible watermark        (L8-3/L8-6)

    Returns:
        (score, description)
        score: -50 (strong AI watermark) to 0 (clean)
    """
    try:
        img = cv2.imread(image_path)
        if img is None:
            return 0, "Error loading image"

        h, w = img.shape[:2]
        if len(img.shape) < 3:
            img_color = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
        else:
            img_color = img

        gray = cv2.cvtColor(img_color, cv2.COLOR_BGR2GRAY)

        # ===== RUN ALL DETECTION METHODS =====

        # 1. L8-1: Visible watermarks (full scan)
        visible = scan_visible_watermarks(gray)

        # 2. L8-2: AI text/logo markers
        ai_text = detect_ai_text_markers(gray)

        # 3. L8-3: Steganography (FP-2: skip on JPEG — JPEG randomizes LSBs)
        if is_jpeg:
            stego = {"score": 0, "description": "Skipped (JPEG invalidates LSB/chi²)"}
        else:
            stego = detect_steganography(gray, img_color)

        # 4. L8-4: Hash-based watermarks
        hash_wm = detect_hash_watermark(gray)

        # 5. L8-5: SynthID / Stable Signature
        synthid = detect_synthid_stable_signature(gray, img_color)

        # 6. L8-3/L8-6: FFT invisible watermark (calibrated)
        invisible = detect_invisible_fft(gray)

        # FP-1: Dampen SynthID/FFT on JPEG (compression creates false correlations)
        if is_jpeg:
            if synthid["score"] < 0 and synthid.get("wavelet_cross_corr", 0) < 0.92:
                synthid["score"] = max(synthid["score"] // 3, -10)
                synthid["description"] = f"JPEG-dampened: {synthid['description']}"
            if invisible["score"] < 0 and invisible.get("max_ratio", 0) < 150:
                invisible["score"] = max(invisible["score"] // 3, -8)
                invisible["description"] = f"JPEG-dampened: {invisible['description']}"

        # ===== LOGGING =====
        print(f"   [Watermark] Visible: {visible['description']}")
        print(f"   [Watermark] AI Text: {ai_text['description']}")
        print(f"   [Watermark] Stego:   {stego['description']}")
        print(f"   [Watermark] Hash:    {hash_wm['description']}")
        print(f"   [Watermark] SynthID: {synthid['description']}")
        print(f"   [Watermark] FFT:     {invisible['description']}")

        # ===== STOCK WATERMARK NEUTRALIZATION =====
        # If we found a visible watermark in a corner/edge position but NO AI
        # text was detected, it's almost certainly a stock/copyright watermark
        # (Shutterstock, Getty, photographer logos) — not an AI generation badge.
        # Neutralize the visible score to prevent false positives on stock photos.
        stock_positions = {"bottom_right", "bottom_left", "bottom_center",
                          "top_right", "top_left", "right_center"}
        if (visible["score"] < -10 and
                ai_text["score"] == 0 and
                visible.get("max_region", "") in stock_positions):
            print(f"   [Watermark] [i] Stock/copyright watermark detected in {visible['max_region']}")
            print(f"   [Watermark]    No AI text found → neutralizing visible score ({visible['score']} → 0)")
            visible["score"] = 0
            visible["description"] = f"Stock watermark in {visible['max_region']} (density:{visible['max_density']:.1f}) — not AI"

        # ===== COMBINE SCORES =====
        all_scores = {
            "visible": visible["score"],
            "ai_text": ai_text["score"],
            "stego":   stego["score"],
            "hash":    hash_wm["score"],
            "synthid": synthid["score"],
            "fft":     invisible["score"],
        }

        # Take the most negative score as primary
        worst_method = min(all_scores, key=all_scores.get)
        worst_score = all_scores[worst_method]

        # Count how many methods flagged something
        flagged = [k for k, v in all_scores.items() if v < -10]

        if len(flagged) >= 3:
            # Multiple methods agree → very strong signal
            combined = int(min(worst_score * 1.2, -50))
            methods_str = ", ".join(flagged)
            return combined, f"Multiple watermarks: {methods_str}"
        elif len(flagged) >= 2:
            combined = worst_score - 5
            return max(combined, -50), f"{worst_method}: {_get_desc(worst_method, visible, ai_text, stego, hash_wm, synthid, invisible)}"
        elif worst_score < -10:
            return worst_score, f"{worst_method}: {_get_desc(worst_method, visible, ai_text, stego, hash_wm, synthid, invisible)}"
        elif worst_score < 0:
            return worst_score, f"Weak signal in {worst_method}"
        else:
            return 0, "No watermarks detected"

    except Exception as e:
        print(f"   [Watermark Error] {e}")
        import traceback
        traceback.print_exc()
        return 0, f"Watermark analysis error: {str(e)}"


def _get_desc(method: str, visible, ai_text, stego, hash_wm, synthid, invisible) -> str:
    """Helper to retrieve description for a specific method."""
    mapping = {
        "visible": visible,
        "ai_text": ai_text,
        "stego":   stego,
        "hash":    hash_wm,
        "synthid": synthid,
        "fft":     invisible,
    }
    return mapping.get(method, {}).get("description", "Unknown")


