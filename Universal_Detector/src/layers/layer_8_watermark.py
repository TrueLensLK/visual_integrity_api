# L8-1: FULL-IMAGE VISIBLE WATERMARK SCAN
# ============================================================================

def scan_visible_watermarks(gray: np.ndarray) -> Dict:
    """
    L8-1 FIX: Scan ALL regions for visible watermarks, not just bottom-right.

    Checks 8 regions: 4 corners + 4 edge-centers + full-image tiled overlay.
    Watermarks from stock sites (Shutterstock, Getty) often tile across the
    center. AI badges appear in various corners.

    Returns:
        Dict with score, description, and per-region results
    """
    h, w = gray.shape
    margin_y = max(int(h * 0.10), 30)
    margin_x = max(int(w * 0.10), 30)

    regions = {
        "top_left":      gray[:margin_y, :margin_x],
        "top_right":     gray[:margin_y, w - margin_x:],
        "bottom_left":   gray[h - margin_y:, :margin_x],
        "bottom_right":  gray[h - margin_y:, w - margin_x:],
        "top_center":    gray[:margin_y, w // 4: 3 * w // 4],
        "bottom_center": gray[h - margin_y:, w // 4: 3 * w // 4],
        "left_center":   gray[h // 4: 3 * h // 4, :margin_x],
        "right_center":  gray[h // 4: 3 * h // 4, w - margin_x:],
    }

    # Also check center strip (stock watermarks)
    center_h = h // 4
    center_w = w // 4
    regions["center_strip"] = gray[center_h: 3 * center_h, center_w: 3 * center_w]

    region_scores = {}
    max_density = 0.0
    max_region = ""

    for name, region in regions.items():
        if region.size < 100:
            continue
        edges = cv2.Canny(region, 80, 200)
        density = float(np.mean(edges))
        region_scores[name] = round(density, 2)
        if density > max_density:
            max_density = density
            max_region = name

    # Tiled watermark detection (stock sites): check if center has
    # repeating high-edge patterns
    tiled_score = 0
    if "center_strip" in region_scores and region_scores["center_strip"] > EDGE_DENSITY_WEAK:
        tiled_score = -15

    # Score based on strongest region
    if max_density > EDGE_DENSITY_STRONG:
        score = -25
        desc = f"Visible watermark in {max_region} (density:{max_density:.1f})"
    elif max_density > EDGE_DENSITY_WEAK:
        score = -12
        desc = f"Possible watermark in {max_region} (density:{max_density:.1f})"
    else:
        score = 0
        desc = "No visible watermarks"

    # Combine tiled overlay penalty
    score = min(score, score + tiled_score)

    return {
        "score": max(score, -30),
        "description": desc,
        "region_scores": region_scores,
        "max_region": max_region,
        "max_density": round(max_density, 2),
    }


