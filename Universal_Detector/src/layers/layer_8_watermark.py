# L8-5: SYNTHID / STABLE SIGNATURE DETECTION
# ============================================================================

def detect_synthid_stable_signature(gray: np.ndarray,
                                     img_color: np.ndarray) -> Dict:
    """
    L8-5 FIX: Detect Google SynthID and Stability AI's Stable Signature.

    SynthID:
      - Embeds an imperceptible pattern into the latent space of Imagen
      - Survives compression, cropping, brightness changes
      - Creates subtle but detectable correlations in wavelet sub-bands

    Stable Signature:
      - Embeds watermark during the VAE decoding step of Stable Diffusion
      - Modifies specific frequency sub-bands of the generated image
      - Detectable via cross-channel correlation in wavelet domain

    Detection methods:
      1. Wavelet cross-band correlation (SynthID signature)
      2. Channel correlation anomaly in mid-frequencies (Stable Signature)
      3. Latent-space periodicity detection (both)
      4. Inter-channel phase coherence (AI watermarks synchronize phases)

    Returns:
        Dict with score and description
    """
    h, w = gray.shape
    reasons = []
    score = 0

    # ---- 1. Wavelet cross-band correlation ----
    # Build a simple wavelet decomposition (Haar-like using Gaussian pyramid)
    subbands = []
    current = gray.astype(np.float64)

    for level in range(4):
        blurred = cv2.GaussianBlur(current, (0, 0), sigmaX=1.5)
        detail = current - blurred
        subbands.append(detail)
        ch, cw = current.shape
        if ch < 64 or cw < 64:
            break
        current = cv2.resize(blurred, (cw // 2, ch // 2),
                             interpolation=cv2.INTER_AREA)
        current = cv2.resize(current, (cw, ch),
                             interpolation=cv2.INTER_LINEAR)

    # Cross-correlate adjacent sub-bands
    # SynthID creates unusual correlations between sub-bands
    cross_corrs = []
    for i in range(len(subbands) - 1):
        a = subbands[i].flatten()
        b = subbands[i + 1].flatten()
        min_len = min(len(a), len(b))
        a, b = a[:min_len], b[:min_len]
        a = a - np.mean(a)
        b = b - np.mean(b)
        denom = np.sqrt(np.sum(a ** 2) * np.sum(b ** 2))
        if denom > 1e-12:
            cc = float(np.sum(a * b) / denom)
            cross_corrs.append(abs(cc))

    avg_cross_corr = float(np.mean(cross_corrs)) if cross_corrs else 0.0

    # Natural images: cross-band correlation ~0.1-0.5
    # SynthID watermarked: correlation pushed to >0.70
    # FP-2: Raised thresholds again — edited/recompressed real images from
    #        Google, social media, stock sites routinely reach 0.85-0.88 due
    #        to sharpening, resize, and multi-generation JPEG compression.
    #        Only flag above 0.92 as definitive; 0.85-0.92 needs phase
    #        coherence corroboration to score at the strong tier.
    if avg_cross_corr > 0.92:
        score -= 30
        reasons.append(f"High wavelet cross-correlation ({avg_cross_corr:.3f}) → SynthID pattern")
    elif avg_cross_corr > 0.85:
        score -= 12
        reasons.append(f"Elevated cross-correlation ({avg_cross_corr:.3f})")

    # ---- 2. Inter-channel phase coherence (Stable Signature) ----
    # Stable Signature embeds during VAE decode → channels become phase-locked
    # Natural images have random phase relationships between R/G/B
    if img_color.shape[2] >= 3:
        phase_coherences = []
        for i in range(3):
            for j in range(i + 1, 3):
                ch_i = img_color[:, :, i].astype(np.float64)
                ch_j = img_color[:, :, j].astype(np.float64)

                f_i = fft2(ch_i)
                f_j = fft2(ch_j)

                phase_i = np.angle(f_i)
                phase_j = np.angle(f_j)

                # Phase difference in mid-frequencies
                cy, cx = h // 2, w // 2
                r_min, r_max = int(min(h, w) * 0.1), int(min(h, w) * 0.4)

                y_g, x_g = np.ogrid[:h, :w]
                r = np.sqrt((x_g - cx) ** 2 + (y_g - cy) ** 2)
                mid_mask = (r > r_min) & (r < r_max)

                phase_diff = phase_i[mid_mask] - phase_j[mid_mask]
                # Circular variance: 0 = perfectly coherent, 1 = random
                coherence = float(abs(np.mean(np.exp(1j * phase_diff))))
                phase_coherences.append(coherence)

        avg_phase_coh = float(np.mean(phase_coherences))

        # Natural: coherence ~0.0-0.25 (random phases between channels)
        # JPEG/processed images: coherence can reach 0.3-0.6 from quantization
        # Stable Signature: coherence >0.70 (synchronized embedding)
        # FP-1: Raised thresholds to avoid JPEG false positives
        if avg_phase_coh > 0.70:
            score -= 28
            reasons.append(f"High phase coherence ({avg_phase_coh:.3f}) → Stable Signature")
        elif avg_phase_coh > 0.55:
            score -= 15
            reasons.append(f"Elevated phase coherence ({avg_phase_coh:.3f})")
    else:
        avg_phase_coh = 0.0

    # ---- 3. Latent-space periodicity (both SynthID & Stable Signature) ----
    # AI-watermarked images show subtle periodic patterns at specific
    # frequencies tied to the latent resolution (typically 64x64 or 128x128)
    latent_sizes = [64, 128]
    latent_score = 0

    for ls in latent_sizes:
        if h < ls * 2 or w < ls * 2:
            continue
        # Check if there's energy at the frequency corresponding to latent size
        freq_y = h // ls
        freq_x = w // ls
        cy, cx = h // 2, w // 2

        f_shift = fftshift(fft2(gray.astype(np.float64)))
        log_mag = 20 * np.log(np.abs(f_shift) + 1e-8)

        # Sample a small region around the latent frequency
        region_size = max(3, min(freq_y // 2, freq_x // 2, 8))
        fy, fx = cy + freq_y, cx + freq_x

        if fy + region_size < h and fx + region_size < w:
            peak_region = log_mag[fy - region_size:fy + region_size,
                                  fx - region_size:fx + region_size]
            bg_mean = float(np.mean(log_mag))
            bg_std = float(np.std(log_mag))
            peak_val = float(np.mean(peak_region))

            if bg_std > 0 and (peak_val - bg_mean) / bg_std > 4.0:
                latent_score -= 12
                reasons.append(f"Latent periodicity at {ls}px grid")

    score += latent_score

    if not reasons:
        return {
            "score": 0,
            "description": "No SynthID/Stable Signature detected",
            "wavelet_cross_corr": round(avg_cross_corr, 4),
            "phase_coherence": round(avg_phase_coh, 4),
        }

    return {
        "score": max(score, -50),
        "description": "; ".join(reasons),
        "wavelet_cross_corr": round(avg_cross_corr, 4),
        "phase_coherence": round(avg_phase_coh, 4),
    }


