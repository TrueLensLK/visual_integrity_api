# L8-3 (continued): FULL-IMAGE INVISIBLE WATERMARK (FFT-based, calibrated)
# ============================================================================

def detect_invisible_fft(gray: np.ndarray) -> Dict:
    """
    Full-image FFT invisible watermark detection with calibrated thresholds.

    L8-3 + L8-6 FIX: Uses the entire image (not just a 64x64 corner)
    and applies calibrated thresholds instead of magic numbers.

    Checks multiple patch sizes to catch watermarks at different scales.

    Returns:
        Dict with score and description
    """
    h, w = gray.shape

    # Analyze at multiple scales
    patch_configs = [
        ("full", gray),
    ]
    # Add quadrant patches for localized watermarks
    qh, qw = h // 2, w // 2
    if qh > 64 and qw > 64:
        patch_configs.extend([
            ("TL", gray[:qh, :qw]),
            ("TR", gray[:qh, qw:]),
            ("BL", gray[qh:, :qw]),
            ("BR", gray[qh:, qw:]),
        ])

    max_ratio = 0.0
    max_patch = ""
    patch_results = {}

    for name, patch in patch_configs:
        if patch.size < 1024:
            continue
        f = fft2(patch.astype(np.float64))
        f_shift = fftshift(f)
        mag = np.abs(f_shift)

        ph, pw = patch.shape
        # Exclude DC component and immediate neighbors
        dc_mask = np.ones_like(mag, dtype=bool)
        cy, cx = ph // 2, pw // 2
        dc_r = max(3, min(ph, pw) // 30)
        y_g, x_g = np.ogrid[:ph, :pw]
        dc_mask[(y_g - cy) ** 2 + (x_g - cx) ** 2 < dc_r ** 2] = False

        masked_mag = mag[dc_mask]
        peak = float(np.max(masked_mag))
        mean = float(np.mean(masked_mag))
        ratio = peak / (mean + 1e-8)

        patch_results[name] = round(ratio, 2)

        if ratio > max_ratio:
            max_ratio = ratio
            max_patch = name

    # L8-6: Calibrated thresholds (replaces old magic *50)
    score = 0
    if max_ratio > FFT_SPIKE_RATIO_STRONG:
        score = -35
        desc = f"Hidden FFT watermark in {max_patch} (ratio:{max_ratio:.1f})"
    elif max_ratio > FFT_SPIKE_RATIO_WEAK:
        score = -18
        desc = f"Possible FFT watermark in {max_patch} (ratio:{max_ratio:.1f})"
    elif max_ratio > 18.0:
        score = -8
        desc = f"Elevated FFT spike in {max_patch} (ratio:{max_ratio:.1f})"
    else:
        desc = f"Clean FFT (max ratio:{max_ratio:.1f})"

    return {
        "score": score,
        "description": desc,
        "max_ratio": round(max_ratio, 2),
        "max_patch": max_patch,
        "patch_results": patch_results,
    }


