# L8-3: PROPER STEGANOGRAPHY DETECTION
# ============================================================================

def detect_steganography(gray: np.ndarray, img_color: np.ndarray) -> Dict:
    """
    L8-3 FIX: Multi-method steganography detection.

    Methods:
      1. Multi-band LSB analysis (R, G, B, Gray - not just one corner)
      2. Chi-square attack (statistical test for LSB embedding)
      3. DCT-domain anomaly detection (JPEG stego tools like JSteg, F5)

    Returns:
        Dict with score and description
    """
    h, w = gray.shape
    results = {}

    # ---- 1. LSB plane analysis (all channels) ----
    channels = {
        "gray": gray,
        "R": img_color[:, :, 2],
        "G": img_color[:, :, 1],
        "B": img_color[:, :, 0],
    }

    lsb_anomalies = []
    for name, ch in channels.items():
        lsb_plane = ch & 1  # Extract least significant bit
        lsb_mean = float(np.mean(lsb_plane))
        lsb_std = float(np.std(lsb_plane.astype(np.float32)))

        # Perfect 50/50 split = suspicious (hidden data randomizes LSBs)
        # Natural images: LSB mean drifts from 0.5, std varies
        deviation_from_half = abs(lsb_mean - 0.5)

        if deviation_from_half < 0.005 and lsb_std > 0.49:
            lsb_anomalies.append(f"{name}(mean={lsb_mean:.4f})")

    results["lsb_anomaly_channels"] = lsb_anomalies

    # ---- 2. Chi-square attack (statistical stego detection) ----
    # Compare histogram of even-valued pixels vs odd-valued
    # In natural images: even/odd counts differ significantly
    # After LSB embedding: they equalize (chi² → expected)
    chi_sq_ratios = []
    for name, ch in channels.items():
        flat = ch.flatten().astype(np.int32)
        hist_256 = np.bincount(flat, minlength=256).astype(np.float64)

        # Pair up: (0,1), (2,3), (4,5), ... → PoVs (Pairs of Values)
        chi_sq = 0.0
        n_pairs = 0
        for i in range(0, 256, 2):
            expected = (hist_256[i] + hist_256[i + 1]) / 2.0
            if expected > 5:  # skip sparse bins
                chi_sq += ((hist_256[i] - expected) ** 2) / expected
                chi_sq += ((hist_256[i + 1] - expected) ** 2) / expected
                n_pairs += 1

        if n_pairs > 0:
            # Normalize: ratio near 1.0 = uniform pairs = stego
            ratio = chi_sq / max(n_pairs, 1)
            chi_sq_ratios.append(ratio)

    avg_chi_ratio = float(np.mean(chi_sq_ratios)) if chi_sq_ratios else 999.0
    results["chi_sq_ratio"] = round(avg_chi_ratio, 4)

    # ---- 3. DCT-domain anomaly (JPEG stego) ----
    # Apply DCT to 8x8 blocks and check coefficient histogram shape
    dct_kurtosis_vals = []
    block_size = 8
    sample_step = max(block_size * 2, h // 30)  # Sample blocks, don't do all

    for y in range(0, h - block_size, sample_step):
        for x in range(0, w - block_size, sample_step):
            block = gray[y:y + block_size, x:x + block_size].astype(np.float64)
            dct_block = dct(dct(block, axis=0, norm='ortho'), axis=1, norm='ortho')
            # Flatten AC coefficients (skip DC at [0,0])
            ac_coeffs = dct_block.flatten()[1:]
            if np.std(ac_coeffs) > 0.01:
                # Kurtosis: natural JPEG has high kurtosis (peaked histogram)
                # Stego flattens it
                mean_ac = np.mean(ac_coeffs)
                std_ac = np.std(ac_coeffs)
                kurt = float(np.mean(((ac_coeffs - mean_ac) / (std_ac + 1e-8)) ** 4))
                dct_kurtosis_vals.append(kurt)

    avg_dct_kurtosis = float(np.mean(dct_kurtosis_vals)) if dct_kurtosis_vals else 5.0
    results["dct_kurtosis"] = round(avg_dct_kurtosis, 3)

    # ---- Scoring ----
    score = 0
    reasons = []

    # LSB anomalies across multiple channels → strong stego signal
    if len(lsb_anomalies) >= 3:
        score -= 30
        reasons.append(f"LSB embedding in {len(lsb_anomalies)} channels")
    elif len(lsb_anomalies) >= 2:
        score -= 20
        reasons.append(f"LSB anomaly in {', '.join(lsb_anomalies)}")
    elif len(lsb_anomalies) == 1:
        score -= 10
        reasons.append(f"LSB anomaly in {lsb_anomalies[0]}")

    # Chi-square close to uniform
    if CHI_SQ_STEGO_LOWER < avg_chi_ratio < CHI_SQ_STEGO_UPPER:
        score -= 25
        reasons.append(f"Chi² stego signature (ratio={avg_chi_ratio:.3f})")
    elif avg_chi_ratio < 1.8:
        score -= 10
        reasons.append(f"Chi² borderline (ratio={avg_chi_ratio:.3f})")

    # DCT kurtosis too low → JPEG stego
    if avg_dct_kurtosis < DCT_KURTOSIS_SUSPICIOUS:
        score -= 15
        reasons.append(f"DCT kurtosis low ({avg_dct_kurtosis:.2f} < {DCT_KURTOSIS_SUSPICIOUS})")

    if not reasons:
        return {"score": 0, "description": "No steganography detected", **results}

    return {
        "score": max(score, -45),
        "description": "; ".join(reasons),
        **results,
    }


